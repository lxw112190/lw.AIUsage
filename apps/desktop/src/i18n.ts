export function useI18n(): {
  locale: Readonly<{ value: Language }>;
  t: (key: string) => string;
} {
  const settings = useSettingsStore();
  const locale = computed(() => settings.language);
  const t = (key: string): string =>
    messages[locale.value][key] ?? messages.en[key] ?? key;
  return { locale, t };
}
